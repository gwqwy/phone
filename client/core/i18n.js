/** 取文案；(n) 形式的键是函数，方便做复数与计数拼接。 */
export function translate(lang, key, arg) {
  const dict = STRINGS[lang] ?? STRINGS.zh
  const value = dict[key] ?? STRINGS.zh[key] ?? key
  return typeof value === 'function' ? value(arg) : value
}
